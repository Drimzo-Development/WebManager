'use strict';
/**
 * Installation steps of the application templates (“New website → Start from”). The catalog the form shows is
 * templates/apps.json; the steps are fixed code here. Downloads come only from the vendor over https and are verified with the
 * vendor's published checksum before anything is unpacked. The database of the website is created by the regular site setup;
 * the application reads its settings from the environment of the container (DB_HOST, DB_DATABASE, DB_USERNAME, DB_PASSWORD),
 * so no password is written into a file and a later password rotation just works.
 */
const crypto = require('crypto');

const SALT_CHARS = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_!@#%^&*()+=';
const WP_SALTS = ['AUTH_KEY', 'SECURE_AUTH_KEY', 'LOGGED_IN_KEY', 'NONCE_KEY', 'AUTH_SALT', 'SECURE_AUTH_SALT', 'LOGGED_IN_SALT', 'NONCE_SALT'];

/** Random string for the WordPress keys (no quotes, backslashes or dollar signs: it ends up inside PHP single quotes). */
function salt(length = 64) {
  const bytes = crypto.randomBytes(length);
  let out = '';
  for (let i = 0; i < length; i++) out += SALT_CHARS[bytes[i] % SALT_CHARS.length];
  return out;
}

/** wp-config.php: database from the environment, fresh keys, HTTPS behind the reverse proxy. */
function wpConfig(salts = Object.fromEntries(WP_SALTS.map((k) => [k, salt()]))) {
  const keys = WP_SALTS.map((k) => `define('${k}', '${salts[k]}');`).join('\n');
  return `<?php
/** Generated by WebManager. The database settings come from the environment of the container. */
define('DB_NAME', getenv('DB_DATABASE'));
define('DB_USER', getenv('DB_USERNAME'));
define('DB_PASSWORD', getenv('DB_PASSWORD'));
define('DB_HOST', getenv('DB_HOST'));
define('DB_CHARSET', 'utf8mb4');
define('DB_COLLATE', '');

${keys}

$table_prefix = 'wp_';

define('WP_DEBUG', false);
define('FS_METHOD', 'direct');

// behind the reverse proxy the visitor uses HTTPS while the container only sees HTTP
if (isset($_SERVER['HTTP_X_FORWARDED_PROTO']) && $_SERVER['HTTP_X_FORWARDED_PROTO'] === 'https') {
    $_SERVER['HTTPS'] = 'on';
}

if (!defined('ABSPATH')) {
    define('ABSPATH', __DIR__ . '/');
}
require_once ABSPATH . 'wp-settings.php';
`;
}

/** Shell script (runs in the website's runtime image, in the project directory): download, verify, unpack. */
const WP_DOWNLOAD = `set -e
cd /app
curl -fsSL --retry 3 --max-time 300 -o /tmp/wordpress.tar.gz https://wordpress.org/latest.tar.gz
curl -fsSL --retry 3 --max-time 60 -o /tmp/wordpress.sha1 https://wordpress.org/latest.tar.gz.sha1
echo "$(tr -d ' \\n\\r' < /tmp/wordpress.sha1)  /tmp/wordpress.tar.gz" | sha1sum -c -
tar -xzf /tmp/wordpress.tar.gz --strip-components=1 -C /app
rm -f /tmp/wordpress.tar.gz /tmp/wordpress.sha1
echo "WordPress files are in place."`;

/**
 * Download script for releases that GitHub publishes with a SHA-256 digest per asset (Joomla, Matomo, Grav). The release list
 * comes from api.github.com, the file only from github.com/<repo>/releases/download/ and is verified against the digest of the
 * release before anything is unpacked. `pattern` is a PCRE for the asset name, `strip` the number of leading directories to drop
 * (tar) or `zipDir` the directory inside a zip archive, `dest` the target directory below /app.
 */
function githubRelease({ repo, pattern, format, strip = 0, zipDir = '', dest = '/app' }) {
  for (const v of [repo, pattern, zipDir, dest]) if (!/^[A-Za-z0-9_./\\+()\[\]*?-]*$/.test(v)) throw new Error('unsafe recipe value');
  const php = '$r=json_decode(file_get_contents($argv[2]),true);foreach($r["assets"]??[] as $a){'
    + 'if(preg_match($argv[1],$a["name"])&&preg_match("/^sha256:[0-9a-f]{64}$/",$a["digest"]??"")){'
    + 'echo $a["browser_download_url"]," ",substr($a["digest"],7);exit(0);}}exit(1);';
  const unpack = format === 'zip'
    ? `unzip -q .wm-tmp/pkg -d .wm-tmp/x\ncp -a ".wm-tmp/x/${zipDir}/." "${dest}/"`
    : `tar -xzf .wm-tmp/pkg --strip-components=${strip} -C "${dest}"`;
  return [
    'set -e',
    'cd /app',
    'rm -rf .wm-tmp && mkdir -p .wm-tmp',
    `mkdir -p "${dest}"`,
    `curl -fsSL --retry 3 --max-time 60 -H 'Accept: application/vnd.github+json' -o .wm-tmp/release.json https://api.github.com/repos/${repo}/releases/latest`,
    `set -- $(php -r '${php}' '~^${pattern}$~' .wm-tmp/release.json) || true`,
    '[ "$#" -eq 2 ] || { echo "No release file with a published checksum was found."; exit 1; }',
    `case "$1" in https://github.com/${repo}/releases/download/*) ;; *) echo "Unexpected download address."; exit 1 ;; esac`,
    'echo "Download $1"',
    'curl -fsSL --retry 3 --max-time 900 -o .wm-tmp/pkg "$1"',
    'echo "$2  .wm-tmp/pkg" | sha256sum -c -',
    unpack,
    'rm -rf .wm-tmp',
    'echo "Files are in place."',
  ].join('\n');
}

/** Nextcloud publishes a .sha256 file next to every archive on its download server. */
const NEXTCLOUD_DOWNLOAD = [
  'set -e',
  'cd /app',
  'rm -rf .wm-tmp && mkdir -p .wm-tmp nextcloud data',
  'B=https://download.nextcloud.com/server/releases/latest.tar.bz2',
  'curl -fsSL --retry 3 --max-time 60 -o .wm-tmp/sum "$B.sha256"',
  'S=$(head -n1 .wm-tmp/sum | cut -d" " -f1)',
  'echo "$S" | grep -Eq "^[0-9a-f]{64}$" || { echo "The published checksum could not be read."; exit 1; }',
  'curl -fsSL --retry 3 --max-time 1500 -o .wm-tmp/pkg "$B"',
  'echo "$S  .wm-tmp/pkg" | sha256sum -c -',
  'tar -xjf .wm-tmp/pkg --strip-components=1 -C nextcloud',
  'rm -rf .wm-tmp',
  'echo "Nextcloud files are in place."',
].join('\n');

/** Nextcloud: the installer reads the database from the environment (no password in a file); the data directory is outside the document root. */
const NEXTCLOUD_AUTOCONFIG = `<?php
/** Generated by WebManager. Used once by the Nextcloud installer, which removes it afterwards. */
$AUTOCONFIG = [
    'dbtype' => 'mysql',
    'dbname' => getenv('DB_DATABASE'),
    'dbuser' => getenv('DB_USERNAME'),
    'dbpass' => getenv('DB_PASSWORD'),
    'dbhost' => getenv('DB_HOST'),
    'directory' => '/var/www/site/data',
];
`;

/** Nextcloud merges config/*.config.php over config.php: a rotated database password keeps working. */
const NEXTCLOUD_ENVCONFIG = `<?php
/** Generated by WebManager: the database settings always come from the environment of the container. */
$CONFIG = [
    'dbhost' => getenv('DB_HOST'),
    'dbname' => getenv('DB_DATABASE'),
    'dbuser' => getenv('DB_USERNAME'),
    'dbpassword' => getenv('DB_PASSWORD'),
];
`;

const GITHUB = {
  joomla: { repo: 'joomla/joomla-cms', pattern: 'Joomla_[0-9.]+-Stable-Full_Package\\.tar\\.gz', format: 'tar', strip: 0 },
  matomo: { repo: 'matomo-org/matomo', pattern: 'matomo-[0-9.]+\\.tar\\.gz', format: 'tar', strip: 1 },
  grav: { repo: 'getgrav/grav', pattern: 'grav-admin-v[0-9.]+\\.zip', format: 'zip', zipDir: 'grav-admin' },
};

const RUN_SCRIPT = 'sh ./.wm-install.sh; rc=$?; rm -f ./.wm-install.sh; rm -rf ./.wm-tmp; exit $rc';

/** Uploads a download script, runs it in the website's runtime and removes it again. */
async function runScript(ctx, site, { runExec, agent, fail }, script, what) {
  ctx.log(`== Download ${what} (checksum is verified)`);
  await agent.putRaw(`/v1/sites/${site.id}/fs/write?path=.wm-install.sh`, script);
  const code = await runExec(ctx, site.id, { kind: 'shell', command: RUN_SCRIPT, timeoutSec: 1800 });
  if (code !== 0) throw fail(`${what} could not be downloaded or verified (exit code ${code})`);
}

const RECIPES = {
  wordpress: {
    async run(ctx, site, { runExec, agent, fail }) {
      ctx.log('== Download WordPress (checksum is verified)');
      const code = await runExec(ctx, site.id, { kind: 'shell', command: WP_DOWNLOAD });
      if (code !== 0) throw fail(`WordPress could not be downloaded or verified (exit code ${code})`);
      ctx.log('== Write wp-config.php');
      await agent.putRaw(`/v1/sites/${site.id}/fs/write?path=wp-config.php`, wpConfig());
    },
  },
  // ships in its image: nothing to download, the container starts with the pinned official image of the runtime (templates/runtimes.json)
  'uptime-kuma': { async run(ctx) { ctx.log('== Uptime Kuma comes with its image: nothing to download.'); } },
  joomla: { run: (ctx, site, deps) => runScript(ctx, site, deps, githubRelease(GITHUB.joomla), 'Joomla') },
  matomo: { run: (ctx, site, deps) => runScript(ctx, site, deps, githubRelease(GITHUB.matomo), 'Matomo') },
  grav: { run: (ctx, site, deps) => runScript(ctx, site, deps, githubRelease(GITHUB.grav), 'Grav') },
  nextcloud: {
    async run(ctx, site, deps) {
      await runScript(ctx, site, deps, NEXTCLOUD_DOWNLOAD, 'Nextcloud');
      ctx.log('== Write the database settings (read from the environment)');
      await deps.agent.putRaw(`/v1/sites/${site.id}/fs/write?path=nextcloud/config/autoconfig.php`, NEXTCLOUD_AUTOCONFIG);
      await deps.agent.putRaw(`/v1/sites/${site.id}/fs/write?path=nextcloud/config/db.config.php`, NEXTCLOUD_ENVCONFIG);
    },
  },
};

const has = (id) => Object.prototype.hasOwnProperty.call(RECIPES, id);

async function install(ctx, site, id, deps) {
  if (!has(id)) throw deps.fail(`Unknown application template: ${String(id).slice(0, 40)}`);
  await RECIPES[id].run(ctx, site, deps);
}

module.exports = { install, has, wpConfig, salt, WP_DOWNLOAD, WP_SALTS, githubRelease, GITHUB, NEXTCLOUD_DOWNLOAD, NEXTCLOUD_AUTOCONFIG, NEXTCLOUD_ENVCONFIG, RUN_SCRIPT };
